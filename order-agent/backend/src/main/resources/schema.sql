CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    unit_price BIGINT NOT NULL CHECK (unit_price >= 0),
    stock_quantity INTEGER NOT NULL CHECK (stock_quantity >= 0),
    active BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS orders (
    id UUID PRIMARY KEY,
    request_id UUID NOT NULL UNIQUE,
    request_hash CHAR(64) NOT NULL,
    customer VARCHAR(64) NOT NULL,
    payment_method VARCHAR(16) NOT NULL CHECK (payment_method IN ('card','prepaid')),
    shipping_country VARCHAR(2) NOT NULL CHECK (shipping_country IN ('KR','US','JP')),
    shipping_express BOOLEAN NOT NULL,
    total_amount BIGINT NOT NULL CHECK (total_amount >= 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('CREATED','PROCESSING','SHIPPED','REJECTED','HOLD','FAILED')),
    result_code VARCHAR(64),
    payment_status VARCHAR(20) NOT NULL,
    payment_reference VARCHAR(80),
    shipment_reference VARCHAR(80),
    estimated_delivery_date DATE,
    notification_status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id),
    sku VARCHAR(64) NOT NULL,
    product_name VARCHAR(120) NOT NULL,
    unit_price BIGINT NOT NULL CHECK (unit_price >= 0),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 99),
    line_total BIGINT NOT NULL CHECK (line_total >= 0),
    UNIQUE(order_id, product_id)
);
CREATE TABLE IF NOT EXISTS order_processing_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    sequence INTEGER NOT NULL,
    step VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL,
    result_code VARCHAR(64),
    message VARCHAR(500) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(order_id, sequence)
);
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON orders(created_at);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status);
CREATE INDEX IF NOT EXISTS idx_items_product ON order_items(product_id);


